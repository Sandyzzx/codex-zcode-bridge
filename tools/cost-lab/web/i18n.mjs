export const MESSAGES = Object.freeze({
  en: Object.freeze(EN),
  "zh-CN": Object.freeze(ZH),
});

export function normalizeLanguage(value) {
  const normalized = String(value ?? "").trim().toLowerCase();
  if (normalized === "zh" || normalized.startsWith("zh-")) return "zh-CN";
  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  return null;
}

export function resolveLanguage(stored, navigatorLanguage) {
  return normalizeLanguage(stored)
    ?? normalizeLanguage(navigatorLanguage)
    ?? "en";
}

export function localeForLanguage(language) {
  return normalizeLanguage(language) === "zh-CN" ? "zh-CN" : "en-US";
}

export function hasMessage(language, key) {
  const normalized = normalizeLanguage(language) ?? "en";
  return Object.hasOwn(MESSAGES[normalized], key) || Object.hasOwn(MESSAGES.en, key);
}

export function translate(language, key, parameters = {}) {
  const normalized = normalizeLanguage(language) ?? "en";
  const template = MESSAGES[normalized]?.[key] ?? MESSAGES.en[key] ?? key;
  return String(template).replace(/\{([a-zA-Z0-9_]+)\}/gu, (match, name) => (
    Object.hasOwn(parameters, name) ? String(parameters[name]) : match
  ));
}

export function applyTranslations(root, language) {
  if (!root?.querySelectorAll) return;
  const t = (key, parameters) => translate(language, key, parameters);
  for (const node of root.querySelectorAll("[data-i18n]")) {
    node.textContent = t(node.dataset.i18n);
  }
  for (const node of root.querySelectorAll("[data-i18n-placeholder]")) {
    node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
  }
  for (const node of root.querySelectorAll("[data-i18n-aria-label]")) {
    node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
  }
  for (const node of root.querySelectorAll("[data-i18n-title]")) {
    node.setAttribute("title", t(node.dataset.i18nTitle));
  }
}
